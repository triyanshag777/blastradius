import tools


def short(n):
    return ".".join(n.split(".")[-2:])


def make_pr_comment(name):
    imp = tools.impact(name)
    tst = tools.tests_for(name)
    exp = tools.experts(name)
    crit = tools.criticality_of(name)

    total = imp["total_dependents"]
    direct = [d["function"] for d in imp["dependents"] if d["hops"] == 1]

    level = "LOW"
    if total >= 15 or (crit and crit["percentile"] <= 10):
        level = "HIGH"
    elif total >= 5:
        level = "MEDIUM"

    lines = [f"## BlastRadius report: `{short(name)}`", ""]
    lines.append(f"**Risk: {level}**. {total} function(s) depend on this code (up to 5 call levels).")
    if crit:
        lines.append(f"Criticality: rank {crit['rank']} of {crit['of']} functions by PageRank (top {crit['percentile']}%).")

    lines += ["", f"**Direct callers ({len(direct)}):** " + (", ".join(f"`{short(d)}`" for d in direct[:8]) or "none")]

    lines += ["", f"**Tests to run ({tst['total_tests']}):**"]
    names = [t["test"].split(".")[-1] for t in tst["tests"][:8]]
    if names:
        lines.append('`pytest -k "' + " or ".join(names) + '"`')
        rest = tst["total_tests"] - len(names)
        if rest > 0:
            lines.append(f"(+ {rest} more tests reach this code)")
    else:
        lines.append("No test reaches this function. Add one before changing it.")

    lines += ["", "**Suggested reviewers (most edits to this file):**"]
    for e in exp["experts"]:
        lines.append(f"- {e['person']} ({e['commits']} commits)")

    lines += ["", "_Generated by BlastRadius from a static call graph (name-based matching). Dynamic calls may be missed._"]
    return "\n".join(lines)


if __name__ == "__main__":
    import sys
    print(make_pr_comment(sys.argv[1]))
